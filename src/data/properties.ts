export const getPropertyById = (id: string): Property | undefined => {
  return properties.find((p) => p.id === id);
};

export const getSimilarProperties = (property: Property, count: number = 3): Property[] => {
  return properties
    .filter(
      (p) =>
        p.id !== property.id &&
        (p.category.some((c) => property.category.includes(c)) ||
          p.type === property.type ||
          p.city === property.city)
    )
    .slice(0, count);
};

export const getFeaturedProperties = (): Property[] => {
  return properties.filter((p) => p.isFeatured);
};

export const getPropertiesByPurpose = (purpose: 'Buy' | 'Rent'): Property[] => {
  return properties.filter((p) => p.purpose === purpose);
};

export const getPropertiesByCategory = (category: string): Property[] => {
  return properties.filter((p) => p.category.includes(category));
};
